r"""Render docs/rbac-matrix.md from policies/rbac_policy.csv.

Usage (from the repository root):
    .\.venv\Scripts\python.exe -m scripts.generate_rbac_matrix            # rewrite the doc
    .\.venv\Scripts\python.exe -m scripts.generate_rbac_matrix --check    # exit 1 if stale
"""
import csv
import sys
from pathlib import Path

from app.authorization.policies import POLICY_PATH
from app.services.identity_service import GATEWAY_ROLES

DOC_PATH = POLICY_PATH.parents[1] / "docs" / "rbac-matrix.md"

# (column label, resource type, action; None = any action)
COLUMNS = [
    ("Invoke models", "model", "invoke"),
    ("Invoke tools", "tool", "invoke"),
    ("Read data sources", "datasource", "read"),
    ("Write data sources", "datasource", "write"),
    ("Admin functions", "admin", None),
]


def parse_policy(path: Path = POLICY_PATH) -> list[tuple[str, str, str]]:
    rules = []
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.reader(handle):
            cells = [c.strip() for c in row]
            if not cells or not cells[0] or cells[0].startswith("#"):
                continue
            if cells[0] != "p" or len(cells) != 4:
                raise ValueError(f"Unsupported policy line: {row}")
            rules.append((cells[1], cells[2], cells[3]))
    return rules


def _cell(rules, role: str, rtype: str, action) -> str:
    patterns = []
    for r, obj, act in rules:
        if r != role:
            continue
        type_ok = obj == "*" or obj.startswith(f"{rtype}:")
        action_ok = act == "*" or action is None or act == action
        if type_ok and action_ok:
            patterns.append(f"`{obj}`")
    return "<br>".join(dict.fromkeys(patterns)) or "—"


def render(rules: list[tuple[str, str, str]]) -> str:
    roles = list(GATEWAY_ROLES) + sorted({r for r, _, _ in rules} - set(GATEWAY_ROLES))
    out = [
        "# RBAC matrix",
        "",
        "<!-- GENERATED by scripts/generate_rbac_matrix.py from policies/rbac_policy.csv. "
        "Do not edit by hand. -->",
        "",
        "Access is **default deny**. A request is allowed only when (1) at least one of the "
        "caller's roles grants the action on the resource, **and** (2) the resource is inside "
        "the caller's token or API-key scopes (when scopes are present). Scopes can narrow a "
        "role but never widen it.",
        "",
        "## Role × capability",
        "",
        "Cells list the resource patterns the role may access. `—` means no access. "
        "`*` matches everything.",
        "",
        "| Role | " + " | ".join(label for label, _, _ in COLUMNS) + " |",
        "|---|" + "---|" * len(COLUMNS),
    ]
    for role in roles:
        cells = [_cell(rules, role, t, a) for _, t, a in COLUMNS]
        out.append(f"| **{role}** | " + " | ".join(cells) + " |")

    out += [
        "",
        "## Raw grants",
        "",
        "| Role | Resource pattern | Action |",
        "|---|---|---|",
    ]
    out += [f"| {r} | `{obj}` | `{act}` |" for r, obj, act in rules]
    out += [
        "",
        "## Resource and action vocabulary",
        "",
        "- Resources: `model:<id>`, `tool:<id>`, `datasource:<id>`, `admin:<area>` "
        "(`admin:roles`, `admin:api-keys`).",
        "- Actions: `invoke`, `read`, `write`, `admin`.",
        "- Patterns are globs (`model:small-*`). Request-supplied identifiers may not contain "
        "wildcards.",
        "",
        "## Changing the matrix",
        "",
        "1. Edit `policies/rbac_policy.csv`.",
        "2. Run `python -m scripts.generate_rbac_matrix` and commit the updated doc.",
        "3. Update the expectation table in `tests/test_rbac.py`.",
        "",
        "CI fails (`tests/test_rbac_doc.py`) if this document is out of date.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    content = render(parse_policy())
    if "--check" in argv:
        current = DOC_PATH.read_text(encoding="utf-8") if DOC_PATH.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print(f"{DOC_PATH} is out of date; run python -m scripts.generate_rbac_matrix")
            return 1
        return 0
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {DOC_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
